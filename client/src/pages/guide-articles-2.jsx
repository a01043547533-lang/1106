function JobfitNow() {
  const st = useApi('/api/jobfit');
  const rows = (st.data?.items || []).filter((r) => !r.past);
  if (!rows.length) return null;
  const sum = (k) => rows.reduce((t, r) => t + (Number(r[k]) || 0), 0);
  const branches = [...new Set(rows.map((r) => r.branch))].join('·');
  return <aside className="note"><p className="note-title">지금 공개된 모집 현황</p><p>{branches}에서 다가오는 입영일 {new Set(rows.map((r) => r.enlistDate)).size}개, 특기 {new Set(rows.map((r) => r.mosCode)).size}개에 모집 {sum('quota')}명 중 <b>남은 자리 {sum('vacancy')}명</b>이에요.</p><p className="note-links"><Link to="/jobfit">입영일별 남은 자리 보기 →</Link></p></aside>;
}

