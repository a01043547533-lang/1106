function ServiceTerms() {
  const terms = useApi('/api/service-terms');
  const list = (terms.data?.items || []).filter((t) => /현역병|사회복무/.test(t.type)).slice(0, 8);
  if (!list.length) return null;
  return <div className="table-wrap"><table className="doc-table"><thead><tr><th>군·유형</th><th className="num">복무기간</th></tr></thead>
    <tbody>{list.map((t) => <tr key={`${t.branch}-${t.type}`}><td>{t.branch} {t.type}</td><td className="num">{t.months}개월</td></tr>)}</tbody></table>
    <p className="muted small">{list[0]?.note}</p></div>;
}

function LotteryNotes() {
  const rules = useApi('/api/rules');
  const lot = rules.data?.lottery || [];
  if (!lot.length) return null;
  return <ul>{lot.map((l) => <li key={`${l.branch}-${l.category}`}><b>{l.branch} {l.category}</b>: {l.note}</li>)}</ul>;
}

