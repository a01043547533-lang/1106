export function GuideArticle() {
  const { slug } = useParams();
  const meta = GUIDES.find((g) => g.slug === slug);
  const Body = ARTICLES[slug];
  // 훅은 조건 없이 먼저 부른다(없는 글로 바뀌어도 훅 개수가 같게).
  const bodyRef = useRef(null);
  const [toc, setToc] = useState([]);
  useEffect(() => {
    const heads = [...(bodyRef.current?.querySelectorAll('h2') || [])];
    heads.forEach((h, i) => { if (!h.id) h.id = `sec-${i + 1}`; });
    setToc(heads.map((h) => ({ id: h.id, text: h.textContent })));
  }, [slug]);
  if (!meta || !Body) return <><PageHeading title="글을 찾을 수 없어요" /><p><Link to="/guide">가이드 목록으로</Link></p></>;
  const others = GUIDES.filter((g) => g.slug !== slug).slice(0, 3);
  return (
    <article className="guide-article">
      <nav className="crumb" aria-label="위치"><Link to="/">입대타이밍</Link> › <Link to="/guide">입대 가이드</Link> › {meta.title}</nav>
      <PageHeading title={meta.title} description={meta.summary} eyebrow="입대 가이드" />
      <p className="muted small">마지막 확인 {meta.updated} · 제도가 바뀌면 병무청 공고가 우선이에요.</p>
      {toc.length > 2 && <nav className="toc" aria-label="이 글의 차례"><p>이 글의 차례</p><ol>{toc.map((t) => <li key={t.id}><a href={`#${t.id}`}>{t.text}</a></li>)}</ol></nav>}
      <div className="card guide-body" ref={bodyRef}><Body /></div>
      <section className="card">
        <h2>다른 가이드</h2>
        <ul>{others.map((g) => <li key={g.slug}><Link to={`/guide/${g.slug}`}>{g.title}</Link></li>)}</ul>
      </section>
    </article>
  );
}
