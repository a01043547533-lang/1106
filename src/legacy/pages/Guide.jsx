function ServiceTermTable() {
  const terms = useApi('/api/service-terms');
  const list = (terms.data?.items || []).filter((t) => ['현역병', '사회복무요원'].includes(t.type) || /현역/.test(t.type)).slice(0, 8);
  if (!list.length) return <Status state={terms} empty="복무기간 데이터를 준비 중이에요" />;
  return <div className="table-wrap"><table className="doc-table">
    <thead><tr><th>군·유형</th><th className="num">복무기간</th></tr></thead>
    <tbody>{list.map((t) => <tr key={`${t.branch}-${t.type}`}><td>{t.branch} {t.type}</td><td className="num">{t.months}개월</td></tr>)}</tbody>
  </table>
  <p className="muted small">{list[0]?.note}</p></div>;
}

